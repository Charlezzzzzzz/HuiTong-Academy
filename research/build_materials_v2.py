# ---------------------------------------------------------------- case helpers

def claim(cid, text, strength, status, sources):
    return {"claim_id": cid, "text": text, "strength": strength, "status": status, "source_ids": sources}


def ev(eid, text, sources, locator, direction):
    return {"evidence_id": eid, "text": text, "source_ids": sources, "locator": locator, "direction": direction}


def link(cid, eid, relation):
    return {"claim_id": cid, "evidence_id": eid, "relation": relation}


def ver(eid, status, note):
    return {"evidence_id": eid, "status": status, "note": note}


def dis(did, text, status, target):
    return {"dissent_id": did, "text": text, "status": status, "target_claim_id": target}


def case(case_id, case_type, topic, question, task, source_ids, claims, evidence, links, verification, dissent,
         gold, scope, anchor):
    return {
        "case_id": case_id,
        "case_type": case_type,
        "topic": topic,
        "question": question,
        "task": task,
        "source_ids": source_ids,
        "claims": claims,
        "evidence": evidence,
        "links": links,
        "verification": verification,
        "dissent": dissent,
        "gold": gold,
        "scope": scope,
        "anchor": anchor,
    }


