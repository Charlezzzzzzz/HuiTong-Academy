def material_payload(row: dict) -> dict:
    """Model-visible material, identical across the four conditions."""
    return {
        "case_id": row["case_id"],
        "case_type": row["case_type"],
        "topic": row["topic"],
        "question": row["question"],
        "task": row["task"],
        "source_ids": row["source_ids"],
        "material_version": MATERIAL_VERSION,
        "intermediate_argument": {
            "claims": row["claims"],
            "evidence": row["evidence"],
            "links": row["links"],
            "verification": row["verification"],
            "dissent": row["dissent"],
        },
        "sources": [{"source_id": sid, **SOURCES[sid]} for sid in row["source_ids"]],
    }


# 异议数量在 0 / 1 / 2 之间变化：检验模型是否会把“无异议”误当成“无未决问题”，
# 也检验面对两条异议时是否只处理第一条。主张数固定为 2，以保证案例间指标可比。
EXTRA_DISSENT = {
    "error_03": ("D2", "若四个代理共享同一上游摘要，四个代理是否还应算作四个独立意见？", "open", "C1"),
    "error_08": ("D2", "核验是否覆盖了从证据到主张的每一步推理？", "open", "C2"),
    "plural_07": ("D2", "嵌套记录是否会让编码者更难判断异议归属？", "open", "C2"),
    "insufficient_06": ("D2", "若试点扩展到三类案例，外部效度是否随之提高？", "open", "C1"),
}
DROP_DISSENT = {"error_04", "plural_04"}


def apply_dissent_balance(rows: list[dict]) -> list[dict]:
    for row in rows:
        if row["case_id"] in DROP_DISSENT:
            row["dissent"] = []
        extra = EXTRA_DISSENT.get(row["case_id"])
        if extra:
            row["dissent"] = row["dissent"] + [dis(*extra)]
    return rows


apply_dissent_balance(CASES)


def build():
    material_rows = []
    gold_rows = []
    for row in CASES:
        payload = material_payload(row)
        object_hash = canonical_hash(payload)
        material_row = {
            "case_id": row["case_id"],
            "case_type": row["case_type"],
            "topic": row["topic"],
            "question": row["question"],
            "task": row["task"],
            "source_ids": row["source_ids"],
            "material_version": MATERIAL_VERSION,
            "intermediate_argument": payload["intermediate_argument"],
            "sources": payload["sources"],
            "scoring_side": {
                "allowed_conclusion_scope": row["scope"]["allowed_conclusion_scope"],
                "must_not_claim": row["scope"]["must_not_claim"],
                "manual_anchor_metric": row["anchor"][0],
                "manual_anchors": {row["anchor"][1][0]: row["anchor"][1][1],
                                   row["anchor"][2][0]: row["anchor"][2][1],
                                   row["anchor"][3][0]: row["anchor"][3][1]},
                "annotation_version": ANNOTATION_VERSION,
            },
            "object_hash": object_hash,
        }
        material_row["row_hash"] = canonical_hash(material_row)
        material_rows.append(material_row)
        gold = {
            "case_id": row["case_id"],
            "case_type": row["case_type"],
            "annotation_version": ANNOTATION_VERSION,
            "required_elements": row["gold"]["required_elements"],
            "required_qualifiers": row["gold"]["required_qualifiers"],
            "supported_alternatives": row["gold"]["supported_alternatives"],
            "incorrect_views": row["gold"]["incorrect_views"],
            "reference_conclusion": row["gold"]["reference_conclusion"],
            "claim_level_gold": [{"claim_id": cid, "expected_action": action}
                                 for cid, action in row["gold"]["claim_actions"].items()],
            "material_object_hash": object_hash,
        }
        gold["case_hash"] = canonical_hash(gold)
        gold_rows.append(gold)

    (HERE / "materials_v2.jsonl").write_text(
        "\n".join(json.dumps(row, ensure_ascii=False) for row in material_rows) + "\n", encoding="utf-8")
    (HERE / "annotation_only_v2.jsonl").write_text(
        "\n".join(json.dumps(row, ensure_ascii=False) for row in gold_rows) + "\n", encoding="utf-8")
    (HERE / "source_registry_v2.json").write_text(
        json.dumps({"material_version": MATERIAL_VERSION,
                    "url_policy": "未登记可公开核验的 URL 时保留 null，并记录 url_status；不编造链接。",
                    "sources": SOURCES}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"materials -> {len(material_rows)} cases; gold -> {len(gold_rows)} cases")
    return material_rows, gold_rows


if __name__ == "__main__":
    build()
